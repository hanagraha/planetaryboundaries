# Create global 1 degree grid for pixel counting
globextent = ee.Geometry.Rectangle([-180, -60, 180, 80], 'EPSG:4326', False)
globgrid = globextent.coveringGrid(ee.Projection('EPSG:4326', [1, 0, -180, 0, -1, 90]))


# ----------------------------------------------------------------------
#                        GET HANSEN TREE COVER LOSS
# ----------------------------------------------------------------------
# Define function to convert tree cover to forest cover
def forest_filter(trees):
    """Filter tree patches >0.5ha (6+ pixels)."""
    patch_size = trees.selfMask().connectedPixelCount(maxSize=6, eightConnected=True)
    return patch_size.gte(6).unmask(0)

# Hansen forest cover loss >= 10% canopy, >= 0.5 ha patch, on land
forest = forest_filter(hansen.select('treecover2000').gte(10)).And(land)

# 255 = no data/water, 99 = stable non-forest, 0 = stable forest, 1-25 = loss year
hansen_forestloss = lossyear.where(forest.Not(), 99).where(land.Not(), 255)


# ----------------------------------------------------------------------
#                          CALCULATE AREA PER CLASS
# ----------------------------------------------------------------------
# Define pixel values
loss_vals = ee.List.sequence(0, 25).cat([99, 255])

# Define function to calculate pixel area
def calc_area(geom):
    """Calculate area (ha) per pixel value."""

    # Clip classification and grid
    classification = hansen_forestloss.clip(geom)
    grid = globgrid.filterBounds(geom)

    # Iterate over pixel values
    def per_value(value):

        # Mask classification by pixel value
        pixelarea = ee.Image.pixelArea().updateMask(classification.eq(ee.Number(value)))

        # Calculate area for each tile
        def per_tile(tile):
            return ee.Feature(None, pixelarea.reduceRegion(
                reducer=ee.Reducer.sum(), geometry=tile.geometry(),
                scale=30, maxPixels=1e13))

        tilearea = grid.map(per_tile)

        # Sum tile areas (m2 to ha)
        return ee.Feature(None, {
            'lossyear': value,
            'area': ee.Number(tilearea.aggregate_sum('area')).divide(10000)
        })

    return ee.FeatureCollection(loss_vals.map(per_value))

# Calculate and export loss area per biome and continent
for k, geom in {**biomes, **continents}.items():
 
    # Calculate area per class
    stats = calc_area(geom)
 
    # Export statistics
    task = ee.batch.Export.table.toDrive(
        collection=stats,
        description=k + '_loss',
        folder='hansen_30m')
    task.start()